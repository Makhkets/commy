// tr translates key; a missing key shows itself rather than nothing.
func tr(lang, key string) string {
	if s, ok := dictionary[lang][key]; ok {
		return s
	}
	if s, ok := dictionary["en"][key]; ok {
		return s
	}
	return key
}

// langOf picks the language: the `lang` cookie, then Accept-Language, then
// Russian.
func langOf(r *http.Request) string {
	if c, err := r.Cookie("lang"); err == nil {
		for _, l := range languages {
			if c.Value == l {
				return l
			}
		}
	}
	accept := strings.ToLower(r.Header.Get("Accept-Language"))
	if accept != "" && !strings.HasPrefix(accept, "ru") && !strings.Contains(accept, "ru-") && !strings.Contains(accept, ",ru") {
		return "en"
	}
	return "ru"
}
